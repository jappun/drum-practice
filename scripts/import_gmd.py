"""Build beats/gmd/ from the Groove MIDI Dataset (CC BY 4.0, Google LLC).

    python scripts/import_gmd.py

Downloads the MIDI-only zip (3 MB) into .cache/gmd/ (git-ignored), checks its
SHA256, picks one 2-bar groove per usable performance and rewrites
beats/gmd/ from scratch, so running it twice gives identical output.
"""

import csv
import hashlib
import json
import sys
import urllib.request
import zipfile
from collections import Counter
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from drum_practice.gmd import Performance, build_beats  # noqa: E402

URL = "https://storage.googleapis.com/magentadata/datasets/groove/groove-v1.0.0-midionly.zip"
SHA256 = "651cbc524ffb891be1a3e46d89dc82a1cecb09a57c748c7b45b844c4841dcc1e"
CACHE = REPO / ".cache" / "gmd"
OUT = REPO / "beats" / "gmd"

ATTRIBUTION = """# Groove MIDI Dataset beats

The beats in this folder are 2-bar excerpts of performances from the
**Groove MIDI Dataset** by Google LLC, licensed under
[Creative Commons Attribution 4.0 International (CC BY 4.0)](https://creativecommons.org/licenses/by/4.0/).

> Jon Gillick, Adam Roberts, Jesse Engel, Douglas Eck, and David Bamman.
> "Learning to Groove with Inverse Sequence Transformations."
> International Conference on Machine Learning (ICML), 2019.

Dataset: https://magenta.tensorflow.org/datasets/groove

**Changes made:** each beat is one 2-bar section of a performance, chosen
as its most repeated groove. Notes were reduced to 10 drum classes,
snapped to a 16th-note grid after removing the drummer's overall
push/pull, and velocities were scaled to each drummer's typical hit and
rounded to ghost / normal / accent. Swung
and triplet-feel performances were left out. Genre labels with fewer than
5 beats are grouped as "Other". Difficulty levels were computed by this
project. Each file's `source` field names the original MIDI file and bars.

Generated by `scripts/import_gmd.py`; don't edit by hand.
"""


def download() -> Path:
    zip_path = CACHE / "groove-v1.0.0-midionly.zip"
    if not zip_path.exists():
        CACHE.mkdir(parents=True, exist_ok=True)
        print(f"Downloading {URL} …")
        urllib.request.urlretrieve(URL, zip_path)
    digest = hashlib.sha256(zip_path.read_bytes()).hexdigest()
    if digest != SHA256:
        zip_path.unlink()
        sys.exit(f"Checksum mismatch ({digest}); deleted the download. Run again.")
    root = CACHE / "groove"
    if not (root / "info.csv").exists():
        with zipfile.ZipFile(zip_path) as z:
            z.extractall(CACHE)
    return root


def load_performances(root: Path) -> list[Performance]:
    with open(root / "info.csv", newline="") as f:
        return [
            Performance(
                midi_filename=row["midi_filename"],
                style=row["style"],
                bpm=int(row["bpm"]),
                beat_type=row["beat_type"],
                time_signature=row["time_signature"],
            )
            for row in csv.DictReader(f)
        ]


def main() -> None:
    root = download()
    beats = build_beats(load_performances(root), root)

    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.json"):
        old.unlink()
    for beat, source in beats:
        data = beat.to_dict()
        data["source"] = source
        (OUT / f"{beat.id}.json").write_text(json.dumps(data, indent=2) + "\n")
    (OUT / "ATTRIBUTION.md").write_text(ATTRIBUTION)

    print(f"Wrote {len(beats)} beats to {OUT.relative_to(REPO)}/")
    for label, counter in (
        ("Genres", Counter(b.genre for b, _ in beats)),
        ("Levels", Counter(b.difficulty for b, _ in beats)),
    ):
        print(f"  {label}: " + ", ".join(f"{k} {v}" for k, v in counter.most_common()))


if __name__ == "__main__":
    main()
